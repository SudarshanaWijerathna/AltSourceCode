// Generates app/brand.css (CSS custom properties) from the dataset's brand pack, so the UI is
// styled from docs/ceylon-compass-dataset/brand/brand_pack.json rather than hand-copied values.
// Runs automatically before `npm run dev` and `npm run build`.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pack = JSON.parse(
  readFileSync(join(here, "..", "..", "docs", "ceylon-compass-dataset", "brand", "brand_pack.json"), "utf8"),
);

const c = pack.colors;
const vars = {
  "--brand-black": c.black,
  "--brand-white": c.white,
  "--brand-orange": c.orange,
  "--brand-surface": c.surface,
  "--brand-text": c.text,
  "--brand-muted": c.muted_text,
  "--brand-border": c.border,
  ...Object.fromEntries(Object.entries(c.accents).map(([k, v]) => [`--accent-${k}`, v])),
  "--font": pack.typography.font_family,
  ...Object.fromEntries(Object.entries(pack.typography.scale_px).map(([k, v]) => [`--fs-${k}`, `${v}px`])),
  ...Object.fromEntries(Object.entries(pack.typography.weights).map(([k, v]) => [`--fw-${k}`, String(v)])),
  ...Object.fromEntries(pack.spacing_px.map((v, i) => [`--sp-${i + 1}`, `${v}px`])),
  "--r-card": `${pack.radius_px.card}px`,
  "--r-button": `${pack.radius_px.button}px`,
  "--r-input": `${pack.radius_px.input}px`,
  "--card-max": `${pack.cards.max_width_px}px`,
  "--t-fast": "150ms", // brand rule: "Transitions under 200 ms"
};

const css = `/* GENERATED by scripts/brand-css.mjs from brand_pack.json — do not edit. */
:root {
${Object.entries(vars).map(([k, v]) => `  ${k}: ${v};`).join("\n")}
}
`;
writeFileSync(join(here, "..", "app", "brand.css"), css);
console.log(`brand.css: ${Object.keys(vars).length} tokens from ${pack.name} brand pack`);
